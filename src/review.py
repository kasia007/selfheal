"""자동 수정이 실패했을 때, 일반적·언어 공통적인 잠재 결함만 훑어 "제안" 을 만듭니다.

수정을 적용하지 않습니다 — 코드를 파일에 쓰지 않고, diff 로 ``--apply`` 대상에
올리지도 않습니다. **업무(도메인) 로직 판단은 하지 않습니다** — 이번 실패의 진짜
원인이 다른 파일과의 연결(예: 라우팅 등록)처럼 그 프로젝트의 구조를 알아야 판단할 수
있는 것이면 건드리지 않습니다. 대신 null/undefined 역참조, 배열·인덱스 경계 초과처럼
언어 공통적으로 흔한 결함 패턴만 찾아 제안합니다 — 이 도구가 원래 py-index·py-dict·
js-head 샘플로 다루던 것과 같은 계열입니다. 최종 판단은 사람이 합니다.

일부러 이번 실행의 진단(``bug_report``)이나 메모리 검색 결과는 컨텍스트로 넣지
않습니다. 넣으면 "이번 실패의 업무적 원인" 쪽으로 LLM 이 끌려가기 쉬워서, 범위를
좁게 유지하려는 의도와 어긋납니다. 소스 코드만 줍니다.
"""

from __future__ import annotations

from .guardrails import wrap_untrusted


def build_suggestion_prompt(language: str, file_name: str, source: str) -> str:
    """줄 번호를 붙인 소스를 주고, 업무 로직 판단은 배제한 채 일반적 결함 패턴만
    찾아 제안하게 하는 프롬프트를 만듭니다."""
    numbered = "\n".join(
        f"{i:>4} | {line}" for i, line in enumerate(source.splitlines(), start=1)
    )
    return (
        f"당신은 {language} 코드를 검토합니다. 지금은 자동 수정이 이미 실패한 뒤라,\n"
        "코드를 다시 쓰는 대신 사람이 읽을 제안만 남기는 자리입니다.\n\n"
        "[지침]\n"
        "1. 이 파일 밖의 원인(다른 파일과의 연결·설정·라우팅 등 업무 구조)은 판단하지 "
        "말고 언급도 하지 마십시오.\n"
        "2. null/undefined 역참조, 배열·인덱스 경계 초과, 명백한 타입 오용처럼 언어 "
        "공통적으로 흔한 결함 패턴만 찾으십시오.\n"
        "3. 파일 전체를 다시 쓰지 마십시오. 발견한 지점마다 아래 형식을 정확히 지켜 "
        "쓰십시오(화면에서 코드와 설명을 구분해서 보여주기 위한 형식입니다):\n"
        "   ### 줄 N\n"
        "   (무엇이 문제일 수 있는지 한두 문장)\n"
        f"   ```{language}\n"
        "   (그 줄 근방을 어떻게 고칠 수 있는지 짧은 예시 코드)\n"
        "   ```\n"
        "4. 아무것도 못 찾으면 '해당 없음' 이라고만 쓰십시오. 억지로 지어내지 마십시오.\n"
        "5. 설명 없이 코드 펜스만 나열하지 말고, 각 제안 앞에 근거를 반드시 문장으로 "
        "쓰십시오. 코드 예시는 항상 ``` 코드 펜스로 감싸십시오 — 감싸지 않으면 화면에서 "
        "설명과 구분되지 않습니다.\n\n"
        f"[파일] {file_name}\n"
        + wrap_untrusted(numbered, "소스")
    )
